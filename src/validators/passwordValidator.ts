export const PW_REGEX = /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[@$!%*?&])[A-Za-z\d@$!%*?&]{8,}$/;

const passwordValidator = (value: string) => {
  return PW_REGEX.test(value);
};

export { passwordValidator };
